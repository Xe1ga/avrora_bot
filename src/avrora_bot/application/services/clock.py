"""Часы клуба: «сегодня» и «сейчас» в часовом поясе клуба (настройка TZ).

Календарные даты, которые бот подставляет сам (кнопка «Сегодня», дата
расхода/передачи/посещения по умолчанию, текущий месяц, остатки на
сегодня), считаются по времени клуба, а не по UTC: иначе запись, сделанная
в Москве между 00:00 и 03:00, попала бы на предыдущий день. Моменты
(``marked_at`` и т. п.) по-прежнему хранятся в UTC.
"""

from datetime import date, datetime
from zoneinfo import ZoneInfo


class ClubClock:
    """Текущие дата и время в часовом поясе клуба."""

    def __init__(self, tz: str) -> None:
        self.tz = ZoneInfo(tz)

    def now(self) -> datetime:
        """Текущий момент (aware) в часовом поясе клуба."""
        return datetime.now(self.tz)

    def today(self) -> date:
        """Сегодняшняя дата по времени клуба."""
        return self.now().date()
